// Package compiler holds private, revisable checks shared by compiler consumers.
package compiler

import (
	"fmt"
	"go/token"
	"go/types"
	"path/filepath"
	"strings"

	"github.com/tylergannon/polytype/grammar"
	"github.com/tylergannon/polytype/typegrammar"

	"golang.org/x/tools/go/packages"
)

// Generated methods are compiler inputs, just like generated schema files. Only
// Polytype's exact ownership marker is admitted; arbitrary JSON hooks are not.
func PolytypeMethod(pkg *packages.Package, fn *types.Func) bool {
	if fn.Pkg() == nil {
		return false
	}
	p := resultPackage(pkg, fn.Pkg().Path())
	if p == nil {
		return false
	}
	for _, file := range p.Syntax {
		if fn.Pos() < file.Pos() || fn.Pos() > file.End() {
			continue
		}
		for _, group := range file.Comments {
			if group.Pos() > file.Package {
				break
			}
			for _, comment := range group.List {
				if comment.Text == "// Code generated by polytype. DO NOT EDIT." {
					return true
				}
			}
		}
	}
	return false
}

func SealedVariants(t types.Type) []types.Type {
	named, ok := types.Unalias(t).(*types.Named)
	if !ok || named.Obj().Pkg() == nil {
		return nil
	}
	iface, ok := named.Underlying().(*types.Interface)
	if !ok {
		return nil
	}
	sealed := false
	for method := range iface.Methods() {
		if !method.Exported() {
			sealed = true
		}
	}
	if !sealed {
		return nil
	}
	var variants []types.Type
	scope := named.Obj().Pkg().Scope()
	for _, name := range scope.Names() {
		obj, ok := scope.Lookup(name).(*types.TypeName)
		if !ok {
			continue
		}
		candidate, ok := obj.Type().(*types.Named)
		if !ok {
			continue
		}
		if _, ok := candidate.Underlying().(*types.Struct); !ok {
			continue
		}
		if types.Implements(candidate, iface) {
			variants = append(variants, candidate)
		} else if types.Implements(types.NewPointer(candidate), iface) {
			variants = append(variants, types.NewPointer(candidate))
		}
	}
	return variants
}

// CheckSplitResponse admits only the demonstrated Polytype validator/decoder
// contract, using Polytype's resolved wire grammar rather than a second wire
// type system. It does not check backend replay effects or transport behavior.
func CheckSplitResponse(pkg *packages.Package, result types.Type, at token.Pos) error {
	fail := func(message string) error { return fmt.Errorf("%s: %s", pkg.Fset.Position(at), message) }
	if err := checkResultMethods(pkg, result, fail); err != nil {
		return err
	}
	if types.TypeString(result, nil) == "github.com/tylergannon/gimbal.Text" {
		return nil
	}
	if _, ok := result.Underlying().(*types.Pointer); ok {
		return fail("Generate result must be a value type")
	}
	for _, name := range []string{"Schema", "ValidateJSON"} {
		method := types.NewMethodSet(result).Lookup(nil, name)
		if method == nil || !PolytypeMethod(pkg, method.Obj().(*types.Func)) {
			return fail("Generate result requires Polytype-generated " + name)
		}
	}
	named, ok := types.Unalias(result).(*types.Named)
	if !ok {
		return fail("Generate result requires a named Polytype type")
	}
	p := resultPackage(pkg, named.Obj().Pkg().Path())
	if p == nil || len(p.GoFiles) == 0 {
		return fail("cannot locate Polytype result package")
	}
	source, err := grammar.Load(filepath.Dir(p.GoFiles[0]))
	if err != nil {
		return fail("load Polytype result contract: " + err.Error())
	}
	definitions, roots, err := source.Lower([]grammar.Root{{Type: result, Position: pkg.Fset.Position(at)}})
	if err != nil {
		return fail("lower Polytype result contract: " + err.Error())
	}
	byName := map[typegrammar.Name]typegrammar.Type{}
	for _, definition := range definitions {
		byName[definition.Name] = definition.Type
		if object, ok := definition.Type.(*typegrammar.Object); ok {
			for _, field := range object.Fields {
				switch field.Value.(type) {
				case *typegrammar.Union, *typegrammar.UnionSlice:
					owner := resultPackage(pkg, definition.Name.PackagePath)
					if owner == nil {
						return fail("cannot locate union owner codec")
					}
					typ, ok := owner.Types.Scope().Lookup(definition.Name.Name).(*types.TypeName)
					if !ok {
						return fail("cannot locate union owner type")
					}
					method := types.NewMethodSet(types.NewPointer(typ.Type())).Lookup(nil, "UnmarshalJSON")
					if method == nil || !PolytypeMethod(pkg, method.Obj().(*types.Func)) {
						return fail("sealed-union result requires a Polytype-generated owner codec")
					}
				}
			}
		}
	}
	visiting := map[typegrammar.Type]bool{}
	checked := map[typegrammar.Type]bool{}
	var visit func(typegrammar.Type) error
	union := func(u typegrammar.Union) error {
		for _, variant := range u.Variants {
			node := byName[variant.Implementation]
			object, ok := node.(*typegrammar.Object)
			if !ok {
				return fail("union variant must be a resolved object")
			}
			for _, field := range object.Fields {
				if strings.EqualFold(field.JSONName, u.Discriminator) {
					return fail("union discriminator collides case-insensitively with variant field " + field.JSONName)
				}
			}
			if err := visit(node); err != nil {
				return err
			}
		}
		return nil
	}
	visit = func(t typegrammar.Type) error {
		if visiting[t] {
			return fail("recursive Generate results are not supported")
		}
		if checked[t] {
			return nil
		}
		visiting[t] = true
		defer func() { delete(visiting, t); checked[t] = true }()
		switch node := t.(type) {
		case *typegrammar.Scalar:
			if node.Kind != typegrammar.String && node.Kind != typegrammar.Bool {
				return fail("Generate result numeric fields require a validator that guarantees Go decoder range and notation; unsupported: " + string(node.Kind))
			}
		case *typegrammar.Enum:
			if node.Kind != typegrammar.String {
				return fail("Generate numeric enums require a demonstrated validator/decoder contract")
			}
		case *typegrammar.Object:
			for _, field := range node.Fields {
				switch value := field.Value.(type) {
				case *typegrammar.Required:
					if err := visit(value.Type); err != nil {
						return err
					}
				case *typegrammar.Union:
					if err := union(*value); err != nil {
						return err
					}
				case *typegrammar.UnionSlice:
					if err := union(value.Union); err != nil {
						return err
					}
				default:
					return fail(fmt.Sprintf("unsupported Generate result field contract %s: %T", field.JSONName, value))
				}
			}
		case *typegrammar.Pointer:
			return visit(node.Element)
		case *typegrammar.Slice:
			return visit(node.Element)
		case *typegrammar.Ref:
			return visit(byName[node.Target])
		default:
			return fail(fmt.Sprintf("unsupported Generate result contract: %T", node))
		}
		return nil
	}
	if err := visit(roots[0]); err != nil {
		return err
	}
	return nil
}

func resultPackage(pkg *packages.Package, path string) *packages.Package {
	seen := map[string]bool{}
	var find func(*packages.Package) *packages.Package
	find = func(p *packages.Package) *packages.Package {
		if p == nil || seen[p.PkgPath] {
			return nil
		}
		seen[p.PkgPath] = true
		if p.PkgPath == path {
			return p
		}
		for _, imported := range p.Imports {
			if found := find(imported); found != nil {
				return found
			}
		}
		return nil
	}
	return find(pkg)
}
