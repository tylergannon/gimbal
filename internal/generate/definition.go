func description(info entryInfo, graph workflow.Graph, page sourcePage, defaults map[string]string) gimbal.WorkflowDescription {
	d := gimbal.WorkflowDescription{Name: graph.Name, Summary: info.summary, Help: info.long, Fields: []gimbal.WorkflowField{}, Roles: map[gimbal.WorkflowRole]string{}}
	properties := map[string]any{}
	required := []string{}
	for _, f := range info.fields {
		name := f.json
		d.Fields = append(d.Fields, gimbal.WorkflowField{Name: name, Flag: f.flag, Kind: f.kind, Description: f.doc, Optional: f.optional})
		kind := f.kind
		if kind == "int" {
			kind = "integer"
		}
		if kind == "bool" {
			kind = "boolean"
		}
		properties[name] = map[string]any{"type": kind}
		if !f.optional {
			required = append(required, name)
		}
	}
	d.InputSchema, _ = json.Marshal(map[string]any{"type": "object", "properties": properties, "required": required, "additionalProperties": false})
	for _, role := range graph.Roles() {
		d.Roles[gimbal.WorkflowRole(role)] = defaults[role]
	}
	d.SourcePage, _ = json.Marshal(page)
	return d
}

func definitionSource(pkg, entry, params string, fields []field, d gimbal.WorkflowDescription, graphExpr, callPrefix string) string {
	raw, _ := json.Marshal(d)
	var b strings.Builder
	fmt.Fprintf(&b, "//go:build !jsonschema\n\n// Code generated by internal/generate. DO NOT EDIT.\npackage %s\nimport(\"context\";\"encoding/json\"\n\n\"github.com/tylergannon/gimbal\"", pkg)
	optional := false
	for _, f := range fields {
		optional = optional || f.optional
	}
	if optional {
		b.WriteString(";\"github.com/tylergannon/polytype\"")
	}
	b.WriteString(")\n")
	fmt.Fprintf(&b, "type generated%sInput struct {\n", entry)
	for _, f := range fields {
		typ := f.kind
		if f.optional {
			typ = "polytype.Optional[" + typ + "]"
		}
		fmt.Fprintf(&b, "%s %s `json:%q`\n", f.name, typ, f.json)
	}
	b.WriteString("}\n")
	fmt.Fprintf(&b, "func %sDefinition() gimbal.WorkflowDefinition {\nvar description gimbal.WorkflowDescription\nif err:=json.Unmarshal([]byte(%q),&description);err!=nil {panic(err)}\nreturn gimbal.WorkflowDefinition{WorkflowDescription:description,Graph:%s,Prepare:func(raw json.RawMessage)(gimbal.Invocation,error){\nif err:=gimbal.ValidateWorkflowInput(description,raw);err!=nil{return nil,err}\nvar input generated%sInput\nif err:=json.Unmarshal(raw,&input);err!=nil{return nil,err}\nreturn func(ctx context.Context,env gimbal.Env) error {return %s%s(ctx,env", entry, string(raw), graphExpr, entry, callPrefix, entry)
	if params != "" {
		fmt.Fprintf(&b, ",%s%s{", callPrefix, params)
		for _, f := range fields {
			fmt.Fprintf(&b, "%s:input.%s,", f.name, f.name)
		}
		b.WriteString("}")
	}
	b.WriteString(")},nil},}\n}\n")
	return b.String()
}

// Definition generates a self-contained workflow definition in the caller's
// module. Its generated Go types preserve omission of optional input values.
func Definition(dir, entry, name string, defaults map[string]string) error {
	dir, err := filepath.Abs(dir)
	if err != nil {
		return err
	}
	file := filepath.Join(dir, "definition_gen.go")
	pkg, err := packageName(dir, file, name)
	if err != nil {
		return err
	}
	if err := checkPolytypeVersion(dir); err != nil {
		return err
	}
	if err := outputSchemaDeclarations(dir, pkg); err != nil {
		return err
	}
	// Generate agent output schemas through the project's pinned Polytype tool.
	tool := exec.Command("go", "tool", "polytype", "--validate")
	tool.Dir = dir
	tool.Stdout = os.Stdout
	tool.Stderr = os.Stderr
	if err := tool.Run(); err != nil {
		return fmt.Errorf("generate: go tool polytype --validate in %s: %w (declare the Polytype tool at the host's pinned version in go.mod)", dir, err)
	}
	inspection := &inspectionData{}
	overlay := map[string][]byte{file: []byte("package " + pkg + "\n"), filepath.Join(dir, "workflow_gen.go"): []byte("package " + pkg + "\n")}
	loaded, err := loadSource(dir, overlay, ".")
	if err != nil {
		return err
	}
	if len(loaded.roots) != 1 {
		return fmt.Errorf("generate: %s holds %d packages", dir, len(loaded.roots))
	}
	graph, info, err := extractLoaded(loaded.roots[0], loaded.imports, entry, name, true, inspection)
	if err != nil {
		return err
	}
	if err = check(info, graph); err != nil {
		return err
	}
	page, err := pageGuide(inspectGraph(graph, entry, inspection), info, graph.Roles(), defaults)
	if err != nil {
		return err
	}
	for _, role := range graph.Roles() {
		if strings.TrimSpace(defaults[role]) == "" {
			return fmt.Errorf("generate: role %s needs --role-default %s=model", role, role)
		}
	}
	source := definitionSource(pkg, entry, info.params, info.fields, description(info, graph, page, defaults), "Graph", "")
	formatted, err := format.Source([]byte(source))
	if err != nil {
		return fmt.Errorf("generate definition: %w", err)
	}
	if err = os.WriteFile(file, formatted, 0644); err != nil {
		return err
	}
	// Inspector graphs include private ordered service markers; persist the ordinary runtime graph.
	graph, _, err = extractLoaded(loaded.roots[0], loaded.imports, entry, name, true, nil)
	if err != nil {
		return err
	}
	return sourceGraph(dir, entry, graph, pkg)
}
func sourceGraph(dir, entry string, graph workflow.Graph, pkg string) error {
	source, err := format.Source([]byte(graphSource(pkg, entry, graph)))
	if err != nil {
		return err
	}
	return os.WriteFile(filepath.Join(dir, "workflow_gen.go"), source, 0644)
}

// outputSchemaDeclarations discovers the concrete local Generate output types.
// Polytype owns their schemas/codecs; authors only declare the ordinary structs.
func outputSchemaDeclarations(dir, pkg string) error {
	files, err := os.ReadDir(dir)
	if err != nil {
		return err
	}
	types := map[string]bool{}
	methods := map[string]bool{}
	for _, file := range files {
		if file.IsDir() || !strings.HasSuffix(file.Name(), ".go") || strings.HasSuffix(file.Name(), "_test.go") || (file.Name() == "output_schema_gen.go" || file.Name() == "jsonschema_gen.go") {
			continue
		}
		tree, err := parser.ParseFile(token.NewFileSet(), filepath.Join(dir, file.Name()), nil, 0)
		if err != nil {
			return err
		}
		for _, decl := range tree.Decls {
			if fn, ok := decl.(*ast.FuncDecl); ok && fn.Name.Name == "Schema" && fn.Recv != nil {
				for _, f := range fn.Recv.List {
					if id, ok := f.Type.(*ast.Ident); ok {
						methods[id.Name] = true
					}
				}
			}
		}
		ast.Inspect(tree, func(node ast.Node) bool {
			index, ok := node.(*ast.IndexExpr)
			if !ok {
				return true
			}
			selector, ok := index.X.(*ast.SelectorExpr)
			if !ok || selector.Sel.Name != "Generate" {
				return true
			}
			if id, ok := index.Index.(*ast.Ident); ok {
				types[id.Name] = true
			}
			return true
		})
	}
	names := []string{}
	for name := range types {
		if !methods[name] {
			names = append(names, name)
		}
	}
	slices.Sort(names)
	if len(names) == 0 {
		err := os.Remove(filepath.Join(dir, "output_schema_gen.go"))
		if err != nil && !os.IsNotExist(err) {
			return err
		}
		return nil
	}
	var source strings.Builder
	fmt.Fprintf(&source, "//go:build jsonschema\n\n// Code generated by internal/generate. DO NOT EDIT.\npackage %s\nimport(\"encoding/json\";\"github.com/tylergannon/polytype\")\n", pkg)
	for _, name := range names {
		fmt.Fprintf(&source, "func(%s) Schema()json.RawMessage{panic(\"schema generation only\")}\nfunc(%s) ValidateJSON([]byte)error{panic(\"schema generation only\")}\nvar _=polytype.Declare(%s.Schema)\n", name, name, name)
	}
	raw, err := format.Source([]byte(source.String()))
	if err != nil {
		return err
	}
	return os.WriteFile(filepath.Join(dir, "output_schema_gen.go"), raw, 0644)
}

func checkPolytypeVersion(dir string) error {
	info, ok := debug.ReadBuildInfo()
	if !ok {
		return nil
	}
	expected := ""
	for _, dep := range info.Deps {
		if dep.Path == "github.com/tylergannon/polytype" {
			expected = dep.Version
			if dep.Replace != nil {
				expected = dep.Replace.Version
			}
			break
		}
	}
	if expected == "" || expected == "(devel)" {
		return nil
	}
	command := exec.Command("go", "list", "-m", "-json", "github.com/tylergannon/polytype")
	command.Dir = dir
	raw, err := command.Output()
	if err != nil {
		return fmt.Errorf("generate: project must pin github.com/tylergannon/polytype %s: %w", expected, err)
	}
	var selected struct {
		Version string
		Replace *struct{ Version string }
	}
	if err := json.Unmarshal(raw, &selected); err != nil {
		return err
	}
	actual := selected.Version
	if selected.Replace != nil {
		actual = selected.Replace.Version
	}
	if actual != expected {
		return fmt.Errorf("generate: project Polytype version %q must match installed host %s", actual, expected)
	}
	return nil
}
