// discoverSchemaTypes finds local named types used as structured Generate
// results. It is intentionally syntax based: a fresh workflow has no
// generated Output methods yet, so type checking it would fail before the
// declaration file can be written.
func discoverSchemaTypes(dir string) ([]string, error) {
	entries, err := os.ReadDir(dir)
	if err != nil {
		return nil, fmt.Errorf("generate: discover schema types: %w", err)
	}
	fset := token.NewFileSet()
	local := map[string]bool{}
	var files []*ast.File
	for _, entry := range entries {
		if entry.IsDir() || !strings.HasSuffix(entry.Name(), ".go") || strings.HasSuffix(entry.Name(), "_test.go") {
			continue
		}
		path := filepath.Join(dir, entry.Name())
		matched, err := build.Default.MatchFile(dir, entry.Name())
		if err != nil {
			return nil, fmt.Errorf("generate: discover schema types: %w", err)
		}
		if !matched || entry.Name() == "schema.go" || strings.HasSuffix(entry.Name(), "_gen.go") {
			continue
		}
		file, err := parser.ParseFile(fset, path, nil, parser.ParseComments)
		if err != nil {
			return nil, fmt.Errorf("generate: discover schema types: %w", err)
		}
		files = append(files, file)
		for _, decl := range file.Decls {
			gen, ok := decl.(*ast.GenDecl)
			if !ok || gen.Tok != token.TYPE {
				continue
			}
			for _, spec := range gen.Specs {
				local[spec.(*ast.TypeSpec).Name.Name] = true
			}
		}
	}
	if len(files) == 0 {
		return nil, fmt.Errorf("generate: discover schema types: no Go source in %s", dir)
	}
	found := map[string]bool{}
	for _, file := range files {
		ast.Inspect(file, func(node ast.Node) bool {
			call, ok := node.(*ast.CallExpr)
			if !ok {
				return true
			}
			if name, ok := generatedType(call.Fun); ok && local[name] {
				found[name] = true
				return false
			}
			if isSetJSON(call.Fun) && len(call.Args) > 2 {
				if name, ok := valueType(call.Args[2]); ok && local[name] {
					found[name] = true
				}
			}
			return true
		})
	}
	types := make([]string, 0, len(found))
	for name := range found {
		types = append(types, name)
	}
	sort.Strings(types)
	return types, nil
}

func generatedType(fun ast.Expr) (string, bool) {
	indexed := fun
	var base ast.Expr
	switch x := indexed.(type) {
	case *ast.IndexExpr:
		base = x.X
	case *ast.IndexListExpr:
		base = x.X
	default:
		return "", false
	}
	sel, ok := base.(*ast.SelectorExpr)
	if !ok || sel.Sel.Name != "Generate" {
		return "", false
	}
	var index ast.Expr
	switch fun := indexed.(type) {
	case *ast.IndexExpr:
		index = fun.Index
	case *ast.IndexListExpr:
		if len(fun.Indices) != 1 {
			return "", false
		}
		index = fun.Indices[0]
	default:
		return "", false
	}
	ident, ok := index.(*ast.Ident)
	if !ok {
		return "", false
	}
	return ident.Name, true
}

func isSetJSON(fun ast.Expr) bool {
	sel, ok := fun.(*ast.SelectorExpr)
	return ok && sel.Sel.Name == "SetJSON"
}

func valueType(expr ast.Expr) (string, bool) {
	if unary, ok := expr.(*ast.UnaryExpr); ok && unary.Op.String() == "&" {
		expr = unary.X
	}
	lit, ok := expr.(*ast.CompositeLit)
	if !ok {
		return "", false
	}
	ident, ok := lit.Type.(*ast.Ident)
	return identName(ident, ok)
}

func identName(ident *ast.Ident, ok bool) (string, bool) {
	if !ok || ident == nil {
		return "", false
	}
	return ident.Name, true
}

func writeSchema(dir, pkg string, names []string) error {
	var b strings.Builder
	b.WriteString("// Code generated by internal/generate. DO NOT EDIT.\n//go:build jsonschema\n\npackage ")
	b.WriteString(pkg)
	b.WriteString("\n\nimport (\n\t\"encoding/json\"\n\n\t\"github.com/tylergannon/polytype\"\n)\n\n")
	for _, name := range names {
		fmt.Fprintf(&b, "func (%s) Schema() json.RawMessage { panic(\"not implemented\") }\n", name)
		fmt.Fprintf(&b, "func (%s) ValidateJSON([]byte) error { panic(\"not implemented\") }\n\n", name)
		fmt.Fprintf(&b, "var _ = polytype.Declare(%s.Schema)\n\n", name)
	}
	formatted, err := format.Source([]byte(b.String()))
	if err != nil {
		return fmt.Errorf("generate: format schema declarations: %w", err)
	}
	return os.WriteFile(filepath.Join(dir, "schema_gen.go"), formatted, 0o644)
}

func runPolytype(dir string) error {
	cmd := exec.Command("go", "tool", "polytype", "--validate")
	cmd.Dir = dir
	var output bytes.Buffer
	cmd.Stdout, cmd.Stderr = &output, &output
	if err := cmd.Run(); err != nil {
		return fmt.Errorf("generate: polytype: %w: %s", err, strings.TrimSpace(output.String()))
	}
	return nil
}

func removeSchemaArtifacts(dir string) error {
	declaration := filepath.Join(dir, "schema_gen.go")
	data, err := os.ReadFile(declaration)
	if os.IsNotExist(err) {
		return nil
	}
	if err != nil {
		return fmt.Errorf("generate: remove schema artifacts: %w", err)
	}
	if !strings.Contains(string(data), "Code generated by internal/generate") {
		return nil
	}
	for _, match := range regexp.MustCompile(`func \(([^)]+)\) Schema\(\)`).FindAllStringSubmatch(string(data), -1) {
		for _, suffix := range []string{".json", ".json.sum"} {
			path := filepath.Join(dir, "jsonschema", match[1]+suffix)
			if err := os.Remove(path); err != nil && !os.IsNotExist(err) {
				return fmt.Errorf("generate: remove schema artifacts: %w", err)
			}
		}
	}
	for _, name := range []string{"jsonschema_gen.go", "polytype_gen.go"} {
		path := filepath.Join(dir, name)
		data, err := os.ReadFile(path)
		if os.IsNotExist(err) {
			continue
		}
		if err != nil {
			return fmt.Errorf("generate: remove schema artifacts: %w", err)
		}
		if !strings.Contains(string(data), "Code generated by polytype") {
			continue
		}
		if err := os.Remove(path); err != nil {
			return fmt.Errorf("generate: remove schema artifacts: %w", err)
		}
	}
	return os.Remove(declaration)
}
