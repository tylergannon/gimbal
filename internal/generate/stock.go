type stockField struct {
	Name, Type, JSON                      string
	Optional, RequiredString, RequiredInt bool
}

type stockData struct {
	Package, Entry, Name, Input, Params string
	Fields                              []stockField
	Optional                            bool
}

// Stock writes the command and invocation sources for the one compiled built-in
// selection. It reads each workflow's actual parameter type and graph roles.
func Stock(root string) error {
	var pages []sourcePage
	var inputs []stockData
	defaults := maps.Clone(builtin.Defaults())
	roleDefaults := map[string]string{}
	for k, v := range defaults {
		roleDefaults[string(k)] = v
	}
	var commands strings.Builder
	commands.WriteString("// Code generated by internal/generate. DO NOT EDIT.\n\npackage main\n\nimport (\n\t\"github.com/spf13/cobra\"\n\t\"github.com/tylergannon/gimbal\"\n)\n\nfunc addStockCommands(run *cobra.Command, defaults map[gimbal.WorkflowRole]string) {\n")
	for _, selected := range builtin.Workflows {
		dir := filepath.Join(root, "internal", "workflows", selected.Package)
		graphFile := filepath.Join(dir, "workflow_gen.go")
		inspection := &inspectionData{}
		graph, info, err := extractInspected(dir, selected.Entry, selected.Name, map[string][]byte{graphFile: []byte("package " + selected.Package + "\n")}, true, inspection)
		if err != nil {
			return err
		}
		if err := check(info, graph); err != nil {
			return err
		}
		command, err := format.Source([]byte(clientCommandSource(selected.Package, selected.Entry, selected.Name, info, graph)))
		if err != nil {
			return fmt.Errorf("generate %s command: %w\n%s", selected.Name, err, clientCommandSource(selected.Package, selected.Entry, selected.Name, info, graph))
		}
		if err := os.WriteFile(filepath.Join(root, "cmd", "gimbal", selected.Command), command, 0o644); err != nil {
			return err
		}
		fmt.Fprintf(&commands, "\trun.AddCommand(%sCommand(defaults))\n", identifier(selected.Package))
		data := stockData{Package: selected.Package, Entry: selected.Entry, Name: selected.Name, Input: "Start" + selected.Entry + "Input", Params: info.params}
		for _, field := range info.fields {
			if field.optional {
				data.Optional = true
			}
			data.Fields = append(data.Fields, stockField{Name: field.name, Type: field.kind, JSON: strings.ReplaceAll(field.flag, "-", "_"), Optional: field.optional, RequiredString: !field.optional && field.kind == "string", RequiredInt: !field.optional && field.kind == "int"})
		}
		p, err := pageGuide(inspectGraph(graph, selected.Entry, inspection), info, graph.Roles(), roleDefaults)
		if err != nil {
			return err
		}
		pages = append(pages, p)
		inputs = append(inputs, data)
		var source strings.Builder
		if err := stockInvocationTemplate.Execute(&source, data); err != nil {
			return err
		}
		formatted, err := format.Source([]byte(source.String()))
		if err != nil {
			return fmt.Errorf("generate %s invocation: %w", selected.Name, err)
		}
		file := filepath.Join(root, "internal", "invocation", selected.Package+"_gen.go")
		if err := os.WriteFile(file, formatted, 0o644); err != nil {
			return err
		}
	}
	if err := writeWorkflowPages(root, pages, inputs); err != nil {
		return err
	}
	commands.WriteString("}\n")
	registry, err := format.Source([]byte(commands.String()))
	if err != nil {
		return fmt.Errorf("generate stock command selection: %w", err)
	}
	return os.WriteFile(filepath.Join(root, "cmd", "gimbal", "stock_workflows_gen.go"), registry, 0o644)
}

func exported(s string) string {
	if s == "" {
		return s
	}
	r := []rune(s)
	r[0] = unicode.ToUpper(r[0])
	return string(r)
}

