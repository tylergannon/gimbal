type stockField struct {
	Name, Type, JSON                      string
	Optional, RequiredString, RequiredInt bool
}

type stockRole struct {
	Name, Field, JSON string
}

type stockData struct {
	Package, Entry, Name, Input, Handler, Params string
	Fields                                       []stockField
	Roles                                        []stockRole
}

// Stock writes the command and Form sources for the one compiled built-in
// selection. It reads each workflow's actual parameter type and graph roles.
func Stock(root string) error {
	var commands strings.Builder
	commands.WriteString("// Code generated by internal/generate. DO NOT EDIT.\n\npackage main\n\nimport (\n\t\"github.com/spf13/cobra\"\n\t\"github.com/tylergannon/gimble\"\n)\n\nfunc addStockCommands(run *cobra.Command, defaults map[gimble.WorkflowRole]string) {\n")
	for _, selected := range builtin.Workflows {
		dir := filepath.Join(root, "internal", "workflows", selected.Package)
		graphFile := filepath.Join(dir, "workflow_gen.go")
		graph, info, err := extract(dir, selected.Entry, selected.Name, map[string][]byte{graphFile: []byte("package " + selected.Package + "\n")})
		if err != nil {
			return err
		}
		if err := check(info, graph); err != nil {
			return err
		}
		command, err := format.Source([]byte(clientCommandSource(selected.Package, selected.Entry, selected.Name, info, graph)))
		if err != nil {
			return fmt.Errorf("generate %s command: %w\n%s", selected.Name, err, clientCommandSource(selected.Package, selected.Entry, selected.Name, info, graph))
		}
		if err := os.WriteFile(filepath.Join(root, "cmd", "gimble", selected.Command), command, 0o644); err != nil {
			return err
		}
		fmt.Fprintf(&commands, "\trun.AddCommand(%sCommand(defaults))\n", identifier(selected.Package))
		data := stockData{Package: selected.Package, Entry: selected.Entry, Name: selected.Name, Input: "Start" + selected.Entry + "Input", Handler: "start" + selected.Entry, Params: info.params}
		for _, field := range info.fields {
			data.Fields = append(data.Fields, stockField{Name: field.name, Type: field.kind, JSON: strings.ReplaceAll(field.flag, "-", "_"), Optional: field.optional, RequiredString: !field.optional && field.kind == "string", RequiredInt: !field.optional && field.kind == "int"})
		}
		for _, role := range graph.Roles() {
			data.Roles = append(data.Roles, stockRole{Name: role, Field: "Role" + exported(identifier(role)), JSON: "role_" + strings.ReplaceAll(role, "-", "_")})
		}
		var source strings.Builder
		if err := stockFormTemplate.Execute(&source, data); err != nil {
			return err
		}
		formatted, err := format.Source([]byte(source.String()))
		if err != nil {
			return fmt.Errorf("generate %s form: %w", selected.Name, err)
		}
		file := filepath.Join(root, "web", "src", "routes", strings.ReplaceAll(selected.Name, "-", "")+"_start.remote.go")
		if err := os.WriteFile(file, formatted, 0o644); err != nil {
			return err
		}
	}
	commands.WriteString("}\n")
	registry, err := format.Source([]byte(commands.String()))
	if err != nil {
		return fmt.Errorf("generate stock command selection: %w", err)
	}
	return os.WriteFile(filepath.Join(root, "cmd", "gimble", "stock_workflows_gen.go"), registry, 0o644)
}

func exported(s string) string {
	if s == "" {
		return s
	}
	r := []rune(s)
	r[0] = unicode.ToUpper(r[0])
	return string(r)
}

