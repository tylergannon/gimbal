// workflowGuide is generated from the same entry and parameter information as
// command help. It is descriptive; it never supplies executable workflow code.
type workflowGuide struct {
	Summary    string           `json:"summary"`
	Prose      string           `json:"prose"`
	Parameters []guideParameter `json:"parameters"`
	Roles      []guideRole      `json:"roles"`
	Invocation string           `json:"invocation"`
	Snapshot   string           `json:"snapshot"`
}
type guideParameter struct {
	Name        string `json:"name"`
	Flag        string `json:"flag"`
	Kind        string `json:"kind"`
	Description string `json:"description"`
	Required    bool   `json:"required"`
}
type guideRole struct {
	Name    string `json:"name"`
	Default string `json:"default"`
}

func pageGuide(p sourcePage, info entryInfo, roles []string, defaults map[string]string) (sourcePage, error) {
	if defaults == nil {
		defaults = map[string]string{}
		for k, v := range builtin.Defaults() {
			defaults[string(k)] = v
		}
	}
	guide := &workflowGuide{Summary: info.summary, Prose: info.long, Parameters: []guideParameter{}, Roles: []guideRole{}}
	guide.Invocation = "gimbal run " + p.Name + " --project /abs/project"
	for _, f := range info.fields {
		required := !f.optional && f.kind != "bool"
		guide.Parameters = append(guide.Parameters, guideParameter{Name: f.name, Flag: f.flag, Kind: f.kind, Description: f.doc, Required: required})
		if required {
			guide.Invocation += " --" + f.flag + " " + map[string]string{"string": strconv.Quote("<" + f.flag + ">"), "int": "1"}[f.kind]
		}
	}
	// Prefer an authored concrete example to generated argument placeholders.
	lines := strings.Split(info.long, "\n")
	for i, line := range lines {
		if strings.HasPrefix(strings.TrimSpace(line), "gimbal run "+p.Name+" ") {
			guide.Invocation = strings.TrimSpace(line)
			for strings.HasSuffix(strings.TrimSpace(lines[i]), "\\") && i+1 < len(lines) {
				i++
				guide.Invocation += "\n  " + strings.TrimSpace(lines[i])
			}
			break
		}
	}
	for _, role := range roles {
		guide.Roles = append(guide.Roles, guideRole{Name: role, Default: defaults[role]})
	}
	p.Guide = guide
	// Shipped descriptors must not depend on or expose the builder's checkout.
	p.Module = ""
	data, err := json.Marshal(p)
	if err != nil {
		return p, err
	}
	hash := sha256.Sum256(data)
	guide.Snapshot = hex.EncodeToString(hash[:])
	return p, nil
}

func writeWorkflowPages(root string, pages []sourcePage, inputs []stockData) error {
	base := filepath.Join(root, "web", "src", "lib", "workflow-design", "generated")
	if err := os.MkdirAll(base, 0755); err != nil {
		return err
	}
	var index strings.Builder
	index.WriteString("// Code generated by internal/generate. DO NOT EDIT.\nexport const workflows=[\n")
	var catalog []map[string]string
	for i, p := range pages {
		fmt.Fprintf(&index, "{name:%q,summary:%q},\n", p.Name, p.Guide.Summary)
		catalog = append(catalog, map[string]string{"name": p.Name, "entry": p.Entry, "dir": "./internal/workflows/" + inputs[i].Package})

	}
	index.WriteString("];\n")
	if err := writeGeneratedFile(filepath.Join(base, "index.ts"), []byte(index.String()), 0644); err != nil {
		return err
	}
	data, err := json.MarshalIndent(catalog, "", "  ")
	if err != nil {
		return err
	}
	return writeGeneratedFile(filepath.Join(base, "catalog.json"), append(data, '\n'), 0644)
}
