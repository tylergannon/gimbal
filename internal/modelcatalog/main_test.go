const fixture = `{
  "openai": {"models": {
    "late": {"id":"z-model","name":"Z","release_date":"2026-01-02","last_updated":"2026-01-03","cost":{"input":4,"output":20,"cache_read":0.4,"cache_write":5}},
    "early": {"id":"a-model","name":"A","release_date":"2026-01-01","last_updated":"2026-01-02","cost":{"input":0.2,"output":1.2,"cache_read":0.02,"cache_write":0.25}},
    "free": {"id":"unpriced","name":"Unpriced"}
  }},
  "anthropic": {"models": {
    "haiku": {"id":"claude-haiku-4-5-20251001","name":"Claude Haiku 4.5","release_date":"2025-10-15","last_updated":"2025-10-15","cost":{"input":1,"output":5,"cache_read":0.1,"cache_write":1.25}}
  }},
  "google": {"models": {
    "flash": {"id":"gemini-3.8-flash","name":"Gemini 3.8 Flash","release_date":"2026-09-02","last_updated":"2026-09-02","cost":{"input":0.75,"output":3.75,"cache_read":0.075}}
  }}
}`

func TestDecodeAndRenderAreDeterministic(t *testing.T) {
	rows, _, err := decode([]byte(fixture))
	if err != nil {
		t.Fatal(err)
	}
	if len(rows) != 4 {
		t.Fatalf("priced rows = %d, want 4", len(rows))
	}
	if rows[0].Provider != "anthropic" || rows[0].ID != "claude-haiku-4-5-20251001" || rows[3].ID != "z-model" {
		t.Fatalf("rows are not sorted by provider and model: %#v", rows)
	}
	if rows[1].ID != "gemini-3.8-flash" || rows[1].CacheWrite != 0 {
		t.Fatalf("optional cache write = %#v, want zero", rows[1])
	}
	first, err := render(rows)
	if err != nil {
		t.Fatal(err)
	}
	rowsAgain, _, err := decode([]byte(fixture))
	if err != nil {
		t.Fatal(err)
	}
	second, err := render(rowsAgain)
	if err != nil {
		t.Fatal(err)
	}
	if !bytes.Equal(first, second) {
		t.Fatal("same catalog bytes rendered different source")
	}
	want := `// Code generated by modelcatalog; DO NOT EDIT.

package observation

var modelPrices = []modelPrice{
	{provider: "anthropic", id: "claude-haiku-4-5-20251001", name: "Claude Haiku 4.5", releaseDate: "2025-10-15", lastUpdated: "2025-10-15", input: 1, output: 5, cacheRead: 0.1, cacheWrite: 1.25},
	{provider: "google", id: "gemini-3.8-flash", name: "Gemini 3.8 Flash", releaseDate: "2026-09-02", lastUpdated: "2026-09-02", input: 0.75, output: 3.75, cacheRead: 0.075, cacheWrite: 0},
	{provider: "openai", id: "a-model", name: "A", releaseDate: "2026-01-01", lastUpdated: "2026-01-02", input: 0.2, output: 1.2, cacheRead: 0.02, cacheWrite: 0.25},
	{provider: "openai", id: "z-model", name: "Z", releaseDate: "2026-01-02", lastUpdated: "2026-01-03", input: 4, output: 20, cacheRead: 0.4, cacheWrite: 5},
}
`
	if string(first) != want {
		t.Fatalf("rendered source:\n%s\nwant:\n%s", first, want)
	}
	for _, row := range rows {
		if row.ID == "unpriced" {
			t.Fatal("model without an input and output price was included")
		}
	}
}

func TestDecodeRejectsMissingProvider(t *testing.T) {
	if _, _, err := decode([]byte(`{"anthropic":{"models":{}},"openai":{"models":{}}}`)); err == nil {
		t.Fatal("decode accepted a catalog without google")
	}
}

func TestAliasesTrackEveryVersionOfEachFamily(t *testing.T) {
	ids := map[string][]string{
		"anthropic": {"claude-sonnet-5", "claude-sonnet-5-5", "claude-sonnet-4-5-20250929", "claude-haiku-4-5", "claude-opus-5-5", "claude-fable-5-1"},
		"openai":    {"gpt-6-sol", "gpt-5.6-terra", "gpt-6-luna", "gpt-6-astra", "gpt-5.5"},
		"diffusion": {"deepseek-4.1-flash", "glm-5.3", "glm-5.3-flash", "glm-5.3-vision", "glm-5.3-vision-background"},
	}
	members, err := resolveAliases(ids)
	if err != nil {
		t.Fatal(err)
	}
	got := map[string]bool{}
	for _, m := range members {
		got[m.Family+" "+m.Version+" "+m.Native] = true
	}
	for _, want := range []string{
		"sonnet 5.5 claude-sonnet-5-5", "sonnet 5 claude-sonnet-5", "terra 5.6 gpt-5.6-terra", "gpt 6 gpt-6-sol",
		"glm 5.3 diffusion/glm-5.3", "glm-vision 5.3 diffusion/glm-5.3-vision",
	} {
		if !got[want] {
			t.Errorf("missing alias member %q in %v", want, members)
		}
	}
	if got["sonnet 4.5 claude-sonnet-4-5-20250929"] || got["glm-vision 5.3 diffusion/glm-5.3-vision-background"] {
		t.Error("dated or variant model ID became an alias member")
	}
}

func TestResolveAliasesRejectsFamilyWithoutModels(t *testing.T) {
	if _, err := resolveAliases(map[string][]string{"anthropic": {"claude-haiku-4-5"}}); err == nil {
		t.Fatal("resolveAliases accepted a catalog missing tracked families")
	}
}

func TestDecodeDiffusionRequiresCompleteChatMetadata(t *testing.T) {
	chat, err := decodeDiffusion([]byte(`{"data":[
		{"id":"b","context_window":10,"max_input_tokens":10,"max_output_tokens":5,"capabilities":["chat","vision"]},
		{"id":"a","context_window":8,"max_input_tokens":8,"max_output_tokens":4,"capabilities":["chat"]},
		{"id":"other","capabilities":["systemone"]}]}`))
	if err != nil || len(chat) != 2 || chat[0].ID != "a" {
		t.Fatalf("decodeDiffusion = %v, %v", chat, err)
	}
	if _, err := decodeDiffusion([]byte(`{"data":[{"id":"x","context_window":8,"capabilities":["chat"]}]}`)); err == nil {
		t.Fatal("decodeDiffusion accepted a chat model without output limits")
	}
}
