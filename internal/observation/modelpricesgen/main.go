// Command modelpricesgen refreshes the generated private model-price table.
package main

import (
	"bytes"
	"context"
	"encoding/json"
	"flag"
	"fmt"
	"go/format"
	"io"
	"net/http"
	"os"
	"path/filepath"
	"sort"
	"strconv"
	"time"
)

const catalogURL = "https://models.dev/api.json"

var providers = []string{"anthropic", "openai", "google"}

type catalog map[string]provider

type provider struct {
	Models map[string]model `json:"models"`
}

type model struct {
	ID          string `json:"id"`
	Name        string `json:"name"`
	ReleaseDate string `json:"release_date"`
	LastUpdated string `json:"last_updated"`
	Cost        *cost  `json:"cost"`
}

type cost struct {
	Input      *float64 `json:"input"`
	Output     *float64 `json:"output"`
	CacheRead  *float64 `json:"cache_read"`
	CacheWrite *float64 `json:"cache_write"`
}

type row struct {
	Provider    string
	ID          string
	Name        string
	ReleaseDate string
	LastUpdated string
	Input       float64
	Output      float64
	CacheRead   float64
	CacheWrite  float64
}

func main() {
	output := flag.String("output", "internal/observation/model_prices_gen.go", "generated Go output")
	url := flag.String("url", catalogURL, "models.dev catalog URL")
	flag.Parse()

	ctx, cancel := context.WithTimeout(context.Background(), 30*time.Second)
	defer cancel()
	raw, err := fetch(ctx, *url)
	if err != nil {
		fatal(err)
	}
	rows, err := decode(raw)
	if err != nil {
		fatal(err)
	}
	source, err := render(rows)
	if err != nil {
		fatal(err)
	}
	if err := os.MkdirAll(filepath.Dir(*output), 0o755); err != nil {
		fatal(fmt.Errorf("create output directory: %w", err))
	}
	if err := os.WriteFile(*output, source, 0o644); err != nil {
		fatal(fmt.Errorf("write %s: %w", *output, err))
	}
}

func fatal(err error) {
	fmt.Fprintln(os.Stderr, "modelpricesgen:", err)
	os.Exit(1)
}

func fetch(ctx context.Context, url string) ([]byte, error) {
	req, err := http.NewRequestWithContext(ctx, http.MethodGet, url, nil)
	if err != nil {
		return nil, fmt.Errorf("build request: %w", err)
	}
	response, err := http.DefaultClient.Do(req)
	if err != nil {
		return nil, fmt.Errorf("download catalog: %w", err)
	}
	defer response.Body.Close()
	if response.StatusCode != http.StatusOK {
		return nil, fmt.Errorf("download catalog: %s", response.Status)
	}
	raw, err := io.ReadAll(response.Body)
	if err != nil {
		return nil, fmt.Errorf("read catalog: %w", err)
	}
	return raw, nil
}

func decode(raw []byte) ([]row, error) {
	var input catalog
	if err := json.Unmarshal(raw, &input); err != nil {
		return nil, fmt.Errorf("decode catalog: %w", err)
	}

	var rows []row
	for _, providerID := range providers {
		provider, ok := input[providerID]
		if !ok {
			return nil, fmt.Errorf("catalog does not contain %q", providerID)
		}
		for _, model := range provider.Models {
			if model.ID == "" || model.Cost == nil || model.Cost.Input == nil || model.Cost.Output == nil {
				continue
			}
			entry := row{
				Provider: providerID, ID: model.ID, Name: model.Name,
				ReleaseDate: model.ReleaseDate, LastUpdated: model.LastUpdated,
				Input: *model.Cost.Input, Output: *model.Cost.Output,
			}
			if model.Cost.CacheRead != nil {
				entry.CacheRead = *model.Cost.CacheRead
			}
			if model.Cost.CacheWrite != nil {
				entry.CacheWrite = *model.Cost.CacheWrite
			}
			rows = append(rows, entry)
		}
	}
	sort.Slice(rows, func(i, j int) bool {
		if rows[i].Provider != rows[j].Provider {
			return rows[i].Provider < rows[j].Provider
		}
		return rows[i].ID < rows[j].ID
	})
	return rows, nil
}

func render(rows []row) ([]byte, error) {
	var out bytes.Buffer
	out.WriteString("// Code generated by modelpricesgen; DO NOT EDIT.\n\n")
	out.WriteString("package observation\n\n")
	out.WriteString("var modelPrices = []modelPrice{\n")
	for _, row := range rows {
		fmt.Fprintf(&out, "\t{provider: %s, id: %s, name: %s, releaseDate: %s, lastUpdated: %s, input: %s, output: %s, cacheRead: %s, cacheWrite: %s},\n",
			quote(row.Provider), quote(row.ID), quote(row.Name), quote(row.ReleaseDate), quote(row.LastUpdated),
			number(row.Input), number(row.Output), number(row.CacheRead), number(row.CacheWrite))
	}
	out.WriteString("}\n")
	source, err := format.Source(out.Bytes())
	if err != nil {
		return nil, fmt.Errorf("format generated source: %w", err)
	}
	return source, nil
}

func quote(value string) string { return strconv.Quote(value) }

func number(value float64) string { return strconv.FormatFloat(value, 'g', -1, 64) }
