// Command rolerefgen generates the documentation site's workflow-role reference.
package main

import (
	"bytes"
	"flag"
	"fmt"
	"go/ast"
	"go/constant"
	"go/parser"
	"go/token"
	"go/types"
	"os"
	"path/filepath"
	"strconv"
	"strings"
)

const (
	minimumDescriptionWords = 10
	maximumDescriptionWords = 20
)

type role struct {
	Name        string
	Value       string
	Description string
}

func main() {
	source := flag.String("source", "roles.go", "Go source containing WorkflowRole constants")
	output := flag.String("output", "docs-site/src/routes/docs/roles/+page.svelte", "generated documentation page")
	flag.Parse()

	roles, err := extract(*source)
	if err != nil {
		fatal(err)
	}
	page := render(roles)
	if err := os.MkdirAll(filepath.Dir(*output), 0o755); err != nil {
		fatal(fmt.Errorf("create output directory: %w", err))
	}
	if err := os.WriteFile(*output, page, 0o644); err != nil {
		fatal(fmt.Errorf("write %s: %w", *output, err))
	}
}

func fatal(err error) {
	fmt.Fprintln(os.Stderr, "rolerefgen:", err)
	os.Exit(1)
}

func extract(filename string) ([]role, error) {
	fset := token.NewFileSet()
	file, err := parser.ParseFile(fset, filename, nil, parser.ParseComments)
	if err != nil {
		return nil, err
	}

	info := &types.Info{Defs: make(map[*ast.Ident]types.Object)}
	config := &types.Config{}
	if _, err := config.Check(file.Name.Name, fset, []*ast.File{file}, info); err != nil {
		return nil, err
	}

	var roles []role
	for _, declaration := range file.Decls {
		group, ok := declaration.(*ast.GenDecl)
		if !ok || group.Tok != token.CONST {
			continue
		}
		for _, rawSpec := range group.Specs {
			spec := rawSpec.(*ast.ValueSpec)
			roleType, ok := spec.Type.(*ast.Ident)
			if !ok || roleType.Name != "WorkflowRole" {
				continue
			}
			comment := spec.Doc
			if comment == nil && len(group.Specs) == 1 {
				comment = group.Doc
			}
			for _, name := range spec.Names {
				if !ast.IsExported(name.Name) {
					continue
				}
				object, ok := info.Defs[name].(*types.Const)
				if !ok || object.Val().Kind() != constant.String {
					return nil, positionedError(fset, name.Pos(), "%s must have a constant string value", name.Name)
				}
				description := descriptionFor(comment, name.Name)
				if description == "" {
					return nil, positionedError(fset, name.Pos(), "%s is missing a description", name.Name)
				}
				wordCount := len(strings.Fields(description))
				if wordCount < minimumDescriptionWords || wordCount > maximumDescriptionWords {
					return nil, positionedError(fset, name.Pos(), "%s description has %d words; want %d to %d", name.Name, wordCount, minimumDescriptionWords, maximumDescriptionWords)
				}
				roles = append(roles, role{
					Name:        name.Name,
					Value:       constant.StringVal(object.Val()),
					Description: description,
				})
			}
		}
	}
	return roles, nil
}

func descriptionFor(comment *ast.CommentGroup, name string) string {
	if comment == nil {
		return ""
	}
	description := strings.Join(strings.Fields(comment.Text()), " ")
	if rest, found := strings.CutPrefix(description, name); found && (rest == "" || strings.HasPrefix(rest, " ")) {
		description = strings.TrimSpace(rest)
	}
	return description
}

func positionedError(fset *token.FileSet, position token.Pos, format string, args ...any) error {
	return fmt.Errorf("%s: %s", fset.Position(position), fmt.Sprintf(format, args...))
}

func render(roles []role) []byte {
	var out bytes.Buffer
	out.WriteString(`<!-- Code generated by rolerefgen from roles.go; DO NOT EDIT. -->

<script lang="ts">
  import DocsPage from "#lib/components/DocsPage.svelte";

  const roles = [
`)
	for _, role := range roles {
		fmt.Fprintf(&out, "    { name: %s, value: %s, description: %s },\n", strconv.Quote(role.Name), strconv.Quote(role.Value), strconv.Quote(role.Description))
	}
	out.WriteString(`  ];

  const headings = roles.map(({ name }) => ({
    id: name.toLowerCase(),
    text: name,
  }));
</script>

<DocsPage
  title="Workflow roles"
  description="The built-in cognitive roles available when binding models to a workflow run."
  eyebrow="Generated reference"
  {headings}
>

<p class="surface rounded-lg px-4 py-3 text-sm"><strong>Generated from <code>roles.go</code>.</strong> Do not edit this page by hand.</p>

{#each roles as role}
  <h2 id={role.name.toLowerCase()}><code>{role.name}</code></h2>
  <dl>
    <dt>Serialized value</dt>
    <dd><code>{role.value}</code></dd>
    <dt>Description</dt>
    <dd>{role.description}</dd>
  </dl>
{/each}

</DocsPage>
`)
	return out.Bytes()
}
