func TestExtractPreservesDeclarationOrderNamesAndResolvedValues(t *testing.T) {
	roles, err := extractFixture(t, `package fixture

type WorkflowRole string

const prefix = "first"

const (
	// RoleFirst handles the first complex assignment with careful reasoning and accurate verification throughout.
	RoleFirst WorkflowRole = prefix + "-role"

	// rolePrivate is not an exported workflow role and must remain undocumented.
	rolePrivate WorkflowRole = "private-role"

	// RoleSecond handles the second complex assignment with clear analysis and reliable validation throughout.
	RoleSecond WorkflowRole = "second-role"
)

const NotARole = "noise"
`)
	if err != nil {
		t.Fatal(err)
	}
	want := []role{
		{Name: "RoleFirst", Value: "first-role", Description: "handles the first complex assignment with careful reasoning and accurate verification throughout."},
		{Name: "RoleSecond", Value: "second-role", Description: "handles the second complex assignment with clear analysis and reliable validation throughout."},
	}
	if len(roles) != len(want) {
		t.Fatalf("roles = %#v, want %#v", roles, want)
	}
	for i := range want {
		if roles[i] != want[i] {
			t.Fatalf("role %d = %#v, want %#v", i, roles[i], want[i])
		}
	}
}

func TestExtractRejectsInvalidDescriptions(t *testing.T) {
	tests := []struct {
		name    string
		comment string
		want    string
	}{
		{name: "missing", want: "fixture.go:4:7: RoleExample is missing a description"},
		{name: "short", comment: "// RoleExample has only eight useful words in this description.\n", want: "fixture.go:5:7: RoleExample description has 8 words; want 10 to 20"},
		{name: "long", comment: "// RoleExample has twenty one distinct words in this deliberately overlong description for generator validation and clear boundary testing right here today now.\n", want: "fixture.go:5:7: RoleExample description has 21 words; want 10 to 20"},
	}
	for _, test := range tests {
		t.Run(test.name, func(t *testing.T) {
			_, err := extractFixture(t, "package fixture\n\ntype WorkflowRole string\n"+test.comment+"const RoleExample WorkflowRole = \"example\"\n")
			if err == nil || !strings.HasSuffix(err.Error(), test.want) {
				t.Fatalf("error = %v, want %q", err, test.want)
			}
		})
	}
}

func TestRenderTracksAddRenameAndRemoveDeterministically(t *testing.T) {
	initialSource := `package fixture
type WorkflowRole string
const (
	// RoleAlpha handles alpha work with deliberate analysis and dependable validation for every assignment.
	RoleAlpha WorkflowRole = "alpha"
	// RoleBeta handles beta work with deliberate analysis and dependable validation for every assignment.
	RoleBeta WorkflowRole = "beta"
)
`
	initial := renderFixture(t, initialSource)
	if bytes.Index(initial, []byte("RoleAlpha")) > bytes.Index(initial, []byte("RoleBeta")) {
		t.Fatal("render changed declaration order")
	}

	changedSource := `package fixture
type WorkflowRole string
const (
	// RoleBetaRenamed handles beta work with deliberate analysis and dependable validation for every assignment.
	RoleBetaRenamed WorkflowRole = "beta-renamed"
	// RoleGamma handles gamma work with deliberate analysis and dependable validation for every assignment.
	RoleGamma WorkflowRole = "gamma"
)
`
	updated := renderFixture(t, changedSource)
	if bytes.Contains(updated, []byte("RoleAlpha")) || bytes.Contains(updated, []byte(`"RoleBeta"`)) {
		t.Fatal("render retained a removed or renamed role")
	}
	if !bytes.Contains(updated, []byte("RoleBetaRenamed")) || !bytes.Contains(updated, []byte("RoleGamma")) {
		t.Fatal("render omitted a renamed or added role")
	}
	if !bytes.Equal(updated, renderFixture(t, changedSource)) {
		t.Fatal("same role catalog rendered different output")
	}
	if !strings.HasPrefix(string(updated), "<!-- Code generated by rolerefgen from roles.go; DO NOT EDIT. -->") {
		t.Fatal("generated page lacks its generated-file label")
	}
}

func renderFixture(t *testing.T, source string) []byte {
	t.Helper()
	roles, err := extractFixture(t, source)
	if err != nil {
		t.Fatal(err)
	}
	return render(roles)
}

func extractFixture(t *testing.T, source string) ([]role, error) {
	t.Helper()
	filename := filepath.Join(t.TempDir(), "fixture.go")
	if err := os.WriteFile(filename, []byte(source), 0o644); err != nil {
		t.Fatal(err)
	}
	return extract(filename)
}
